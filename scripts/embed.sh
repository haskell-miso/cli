#!/bin/sh
# embed.sh OUT DIR FILE...: a Haskell module, Miso.CLI.DocsViewer, with the
# files (paths relative to DIR) as strings.  miso docs writes them out.
set -e
out=$1; dir=$2; shift 2
mkdir -p "$(dirname "$out")"
{
  echo "-- Generated by scripts/embed.sh from $dir/: do not edit."
  echo "module Miso.CLI.DocsViewer (viewerFiles) where"
  echo ""
  echo "viewerFiles :: [(FilePath, String)]"
  echo "viewerFiles ="
  sep="["
  for f in "$@"; do
    echo "  $sep (\"$f\", unlines"
    awk 'BEGIN { s = "      [" }
         { gsub(/\\/, "\\\\"); gsub(/"/, "\\\""); gsub(/\t/, "\\t"); print s " \"" $0 "\""; s = "      ," }
         END { if (NR == 0) print "      ["; print "      ])" }' "$dir/$f"
    sep=","
  done
  echo "  ]"
} > "$out"
